-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT program.ID AS ENTITY_ID, program.NAME AS ENTITY_NAME,
       program.REGION, program.CATEGORY, program.RISK_TIER, program.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.CONTACT_COUNT) AS CONTACT_COUNT,
       SUM(observation.BILLABLE_PHP) AS BILLABLE_PHP,
       SUM(observation.INCIDENT_COUNT) AS INCIDENT_COUNT,
       SUM(observation.BREACH_COUNT) AS BREACH_COUNT,
       SUM(observation.PENALTY_FLAGGED) AS PENALTY_COUNT,
       SUM(observation.AUDIT_DUE) AS AUDIT_DUE,
       SUM(observation.AUDIT_COMPLETED) AS AUDIT_COMPLETED,
       100.0 * (SUM(observation.CONTACT_COUNT) - SUM(observation.INCIDENT_COUNT)) / NULLIF(SUM(observation.CONTACT_COUNT), 0) AS INCIDENT_FREE_PCT,
       100.0 * SUM(observation.BREACH_COUNT) / NULLIF(SUM(observation.INCIDENT_COUNT), 0) AS INCIDENT_BREACH_PCT,
       100.0 * SUM(observation.AUDIT_COMPLETED) / NULLIF(SUM(observation.AUDIT_DUE), 0) AS AUDIT_COMPLIANCE_PCT,
       AVG(observation.ABANDON_PCT) AS AVG_ABANDON_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PROGRAM_DAILY observation
JOIN RAW.PROGRAMS program ON program.ID = observation.ENTITY_ID
GROUP BY program.ID, program.NAME, program.REGION, program.CATEGORY, program.RISK_TIER, program.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(CONTACT_COUNT) AS CONTACT_COUNT, SUM(BILLABLE_PHP) AS BILLABLE_PHP,
       SUM(INCIDENT_COUNT) AS INCIDENT_COUNT, SUM(BREACH_COUNT) AS BREACH_COUNT,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(INCIDENT_COUNT), 0) AS INCIDENT_BREACH_PCT
FROM RAW.PROGRAM_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.INCIDENT_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT INCIDENT_TYPE, SUM(INCIDENT_COUNT) AS INCIDENT_COUNT,
       SUM(BREACH_COUNT) AS BREACH_COUNT,
       SUM(PENALTY_FLAGGED) AS PENALTY_COUNT,
       SUM(BILLABLE_PHP) AS EXPOSED_BILLABLE_PHP,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(INCIDENT_COUNT), 0) AS INCIDENT_BREACH_PCT
FROM RAW.PROGRAM_DAILY
WHERE INCIDENT_COUNT > 0
GROUP BY INCIDENT_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(CONTACT_COUNT) AS CONTACTS, SUM(INCIDENT_COUNT) AS INCIDENTS,
         SUM(BREACH_COUNT) AS BREACHED, SUM(PENALTY_FLAGGED) AS PENALTIES, SUM(BILLABLE_PHP) AS BILLABLE_PHP,
         SUM(AUDIT_DUE) AS AUDIT_DUE, SUM(AUDIT_COMPLETED) AS AUDIT_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PROGRAM_DAILY
), book AS (SELECT COUNT(*) AS PROGRAM_COUNT FROM RAW.PROGRAMS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.CONTROL_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Incident-Free Contact Rate' AS TITLE,
         100.0 * (CONTACTS - INCIDENTS) / NULLIF(CONTACTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Incidents Raised', INCIDENTS, '' FROM observations
  UNION ALL SELECT 3, 'SLA-Breach Incidents', BREACHED, '' FROM observations
  UNION ALL SELECT 4, 'Incident Breach Rate', 100.0 * BREACHED / NULLIF(INCIDENTS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Penalty Notices', PENALTIES, '' FROM observations
  UNION ALL SELECT 6, 'Billable Value (PHP M)', BILLABLE_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Contacts Handled', CONTACTS, '' FROM observations
  UNION ALL SELECT 8, 'QA Calibration Compliance', 100.0 * AUDIT_COMPLETED / NULLIF(AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Programs Monitored', PROGRAM_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Client Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Client Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.INCIDENT_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
